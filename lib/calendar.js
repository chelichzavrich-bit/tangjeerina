const DEFAULT_STATE = {
  key: null, kind: 'normal', title: '', mood: 1, max: 0,
  games: true, pulse: true, strip: false, block: '', occasion: null
};

function state(now = new Date()) {
  if (!ENABLED) return { ...DEFAULT_STATE };
  const p = parts(now);
  const ev = EVENTS.find((e) => e.m === p.m && e.d === p.d);
  if (!ev) return { ...DEFAULT_STATE };
  return { ...DEFAULT_STATE, ...ev };
}

