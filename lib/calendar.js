// ───────────── дата в её часовом поясе ─────────────
let fmtCache = null;
function parts(now = new Date()) {
  let p = null;
  try {
    if (!fmtCache) {
      fmtCache = new Intl.DateTimeFormat('en-GB', {
        timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', hour12: false
      });
    }
    const o = {};
    for (const it of fmtCache.formatToParts(now)) o[it.type] = it.value;
    p = { y: Number(o.year), m: Number(o.month), d: Number(o.day), h: Number(o.hour) % 24 };
  } catch (_) {
    const shifted = new Date(now.getTime() - 5 * 3600000);
    p = { y: shifted.getUTCFullYear(), m: shifted.getUTCMonth() + 1, d: shifted.getUTCDate(), h: shifted.getUTCHours() };
  }
  // Тестовая дата: CALENDAR_TEST_DATE=08-27 позволяет проверить любой день, не дожидаясь его.
  const test = /^(\d{1,2})-(\d{1,2})$/.exec(str('CALENDAR_TEST_DATE', ''));
  if (test) {
    const m = Number(test[1]);
    const d = Number(test[2]);
    if (m >= 1 && m <= 12 && d >= 1 && d <= 31) { p.m = m; p.d = d; }
  }
  return p;
}

function daysUntil(m, d, now = new Date()) {
  const p = parts(now);
  const today = Date.UTC(p.y, p.m - 1, p.d);
  let target = Date.UTC(p.y, m - 1, d);
  if (target < today) target = Date.UTC(p.y + 1, m - 1, d);
  return Math.round((target - today) / 86400000);
}

