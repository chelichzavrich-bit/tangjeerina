const num = (name, def) => {
  const raw = process.env[name];
  if (raw === undefined || raw === '') return def;
  const v = Number(raw);
  return Number.isFinite(v) ? v : def;
};
const flag = (name, def) => {
  const raw = String(process.env[name] === undefined ? '' : process.env[name]).trim().toLowerCase();
  if (!raw) return def;
  return !['0', 'off', 'false', 'no'].includes(raw);
};
const str = (name, def) => {
  const raw = process.env[name];
  return raw === undefined || raw === '' ? def : String(raw).trim();
};

const TZ = str('CALENDAR_TZ', 'Etc/GMT+5'); // Etc/GMT+5 = UTC-5, знак в названии зоны обратный
const ENABLED = flag('CALENDAR', true);
const STRICT = flag('CALENDAR_STRICT', true);   // жёстко резать длину и убирать смайлики в тяжёлые дни
