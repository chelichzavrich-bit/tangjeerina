// Повод написать первой (минует ожидание тишины, но не тихие часы).
function pulseOccasion(now = new Date()) {
  if (!ENABLED) return null;
  const p = parts(now);
  const s = state(now);
  if (s.occasion) return { tag: p.y + '-' + s.key, prompt: s.occasion };
  if (daysUntil(3, 31, now) === 3) {
    return {
      tag: p.y + '-tang_bday_soon',
      prompt: 'До твоего дня рождения (31 марта) осталось три дня. Напиши в чат ПЕРВА: напомни всем, что скоро главный праздник года, потребуй подарки заранее и объяви, кто уже в должниках. 2-3 предложения, ломаный русский, один смайлик в конце.'
    };
  }
  return null;
}

// ───────────── жёсткие ограничения на текст ─────────────
const WEAPON_EMOJI = /(☺️|☺|🤗|😋|🤭|🫣)/g;

function limitReply(text, now = new Date()) {
  const s = state(now);
  let out = String(text || '').trim();
  if (!out) return out;
  if (STRICT && s.strip) {
    out = out.replace(WEAPON_EMOJI, '').replace(/[ \t]{2,}/g, ' ').replace(/\s+([.,!?])/g, '$1').trim();
  }
  const max = s.max;
  if (!max || max >= 99) return out;
  const sentences = out.match(/[^.!?…]+[.!?…]+|[^.!?…]+$/g) || [out];
  if (sentences.length <= max) return out;
  out = sentences.slice(0, max).join(' ').trim();
  const tail = /(☺️|🤗|😋|🤭|🫣)\s*$/.exec(String(text || ''));
  if (tail && !s.strip && !out.endsWith(tail[1])) out = out.replace(/[.!?…\s]+$/, '') + ' ' + tail[1];
  if (!/[.!?…]$/.test(out)) out += '.';
  return out.trim();
}

