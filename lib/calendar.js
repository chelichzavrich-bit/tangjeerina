function moodFactor(now = new Date()) {
  const base = (ctx && typeof ctx.moodFactor === 'function') ? ctx.moodFactor(now) : 1;
  return base * state(now).mood;
}
function spontAllowed(now = new Date()) {
  const s = state(now);
  return s.kind !== 'shutdown';
}
