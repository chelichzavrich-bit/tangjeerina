function block(now = new Date()) {
  return state(now).block || '';
}

// Напоминания о крупных праздниках (только про свои радости, не про боль).
function reminderBlock(now = new Date()) {
  if (!ENABLED || REMIND_DAYS <= 0) return '';
  const left = daysUntil(3, 31, now);
  if (left > 0 && left <= REMIND_DAYS) {
    return '[КАЛЕНДАРЬ: до твоего дня рождения (31 марта) осталось ' + left + ' дн. Ты уже начала требовать подарки и напоминать всем, что ты главная. Вплети это одной фразой, если уместно, и записывай должников. Не превращай в это весь ответ.]';
  }
  const city = daysUntil(12, 25, now);
  if (city > 0 && city <= 3) {
    return '[КАЛЕНДАРЬ: через ' + city + ' дн День Города XM-CITY, главный праздник твоего государства и день твоего знакомства с Жаком. Ты в предвкушении добычи. Можешь одной фразой этим похвастаться.]';
  }
  return '';
}

