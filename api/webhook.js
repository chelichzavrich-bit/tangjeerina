// parts - массив частей Gemini: [{text}] или [{text}, {inline_data}]
async function callGemini(model, parts, temperature) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;
    const r = await fetch(url, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'x-goog-api-key': process.env.GEMINI_API_KEY
        },
        body: JSON.stringify({
            systemInstruction: { parts: [{ text: FULL_SYSTEM_INSTRUCTION }] },
            contents: [{ role: 'user', parts }],
            generationConfig: { temperature, maxOutputTokens: 4096 },
            safetySettings: SAFETY_SETTINGS
        })
    });

    const raw = await r.text();
    let data = {};
    try { data = JSON.parse(raw); } catch (_) { /* не JSON */ }

    if (!r.ok) {
        const err = new Error(`Gemini ${model} HTTP ${r.status}: ${(data.error && data.error.message) || raw.slice(0, 300)}`);
        err.status = r.status;
        throw err;
    }

    const cand = data.candidates && data.candidates[0];
    const text = cand && cand.content && Array.isArray(cand.content.parts)
        ? cand.content.parts.filter((p) => p.text && !p.thought).map((p) => p.text).join('').trim()
        : '';
    return text; // пустая строка = ответ заблокирован фильтром или пуст
}

function cleanReply(text) {
    // персонажу запрещено длинное тире
    return text.replace(/\s*[—–]\s*/g, ' - ');
}

async function generateReply(parts, temperature = 1.0) {
    if (!process.env.GEMINI_API_KEY) throw new Error('GEMINI_API_KEY is not set');
    let lastError;
    for (const model of MODEL_CHAIN) {
        try {
            const text = await callGemini(model, parts, temperature);
            return text ? cleanReply(text) : FALLBACK_REPLY;
        } catch (e) {
            lastError = e;
            console.error(String(e.message));
            // 404 (модель снята), 429 (лимит), 5xx (перегрузка), 400 (неподдерживаемый параметр) -> следующая модель
            if ([400, 404, 429, 500, 502, 503, 504].includes(e.status)) continue;
            throw e; // 401/403 (плохой ключ) - перебор бессмысленен
        }
    }
    throw lastError || new Error('No model available');
}

async function telegram(method, payload) {
    const token = process.env.TELEGRAM_BOT_TOKEN;
    if (!token) throw new Error('TELEGRAM_BOT_TOKEN is not set');
    const r = await fetch(`https://api.telegram.org/bot${token}/${method}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
    });
    const body = await r.text();
    if (!r.ok) throw new Error(`Telegram ${method} HTTP ${r.status}: ${body.slice(0, 300)}`);
    try { return JSON.parse(body); } catch (_) { return {}; }
}

async function sendTelegramMessage(chatId, text, replyToMessageId) {
    const LIMIT = 4000; // лимит Telegram - 4096
    const chunks = [];
    for (let i = 0; i < text.length; i += LIMIT) chunks.push(text.slice(i, i + LIMIT));
    for (let i = 0; i < chunks.length; i++) {
        const payload = { chat_id: chatId, text: chunks[i] };
        if (i === 0 && replyToMessageId) {
            payload.reply_parameters = { message_id: replyToMessageId, allow_sending_without_reply: true };
        }
        await telegram('sendMessage', payload);
    }
}

// Скачивает картинку из Telegram и возвращает часть inline_data для Gemini (или null)
async function fetchTelegramImage(msg) {
    let fileId = null;
    let mime = 'image/jpeg';
    let size = 0;

    if (Array.isArray(msg.photo) && msg.photo.length) {
        const best = msg.photo[msg.photo.length - 1]; // самое большое превью
        fileId = best.file_id;
        size = best.file_size || 0;
    } else if (msg.document && /^image\//.test(msg.document.mime_type || '')) {
        fileId = msg.document.file_id;
        mime = msg.document.mime_type;
        size = msg.document.file_size || 0;
    } else if (msg.sticker && !msg.sticker.is_animated && !msg.sticker.is_video) {
        fileId = msg.sticker.file_id;
        mime = 'image/webp';
        size = msg.sticker.file_size || 0;
    }
    if (!fileId || size > MAX_IMAGE_BYTES) return null;

    const info = await telegram('getFile', { file_id: fileId });
    const filePath = info && info.result && info.result.file_path;
    if (!filePath) return null;

    const r = await fetch(`https://api.telegram.org/file/bot${process.env.TELEGRAM_BOT_TOKEN}/${filePath}`);
    if (!r.ok) throw new Error(`Telegram file download HTTP ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length > MAX_IMAGE_BYTES) return null;
    return { inline_data: { mime_type: mime, data: buf.toString('base64') } };
}

function parseBody(req) {
    if (typeof req.body === 'string') {
        try { return JSON.parse(req.body); } catch (_) { return null; }
    }
    return req.body || null;
}

