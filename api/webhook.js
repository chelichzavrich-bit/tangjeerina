const chatHistories = new Map();

async function callGemini(model, contents, temperature) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;
    const r = await fetch(url, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'x-goog-api-key': process.env.GEMINI_API_KEY
        },
        body: JSON.stringify({
            systemInstruction: { parts: [{ text: FULL_SYSTEM_INSTRUCTION }] },
            contents: contents,
            generationConfig: { temperature, maxOutputTokens: 4096 },
            safetySettings: SAFETY_SETTINGS
        })
    });

    const raw = await r.text();
    let data = {};
    try { data = JSON.parse(raw); } catch (_) {}

    if (!r.ok) {
        const err = new Error(`Gemini ${model} HTTP ${r.status}: ${(data.error && data.error.message) || raw.slice(0, 300)}`);
        err.status = r.status;
        throw err;
    }

    const cand = data.candidates && data.candidates[0];
    const text = cand && cand.content && Array.isArray(cand.content.parts)
        ? cand.content.parts.filter((p) => p.text && !p.thought).map((p) => p.text).join('').trim()
        : '';
    return text;
}

function cleanReply(text) {
    return text.replace(/\s*[—–]\s*/g, ' - ');
}

async function generateReplyWithHistory(chatId, newParts, temperature = 1.0) {
    if (!process.env.GEMINI_API_KEY) throw new Error('GEMINI_API_KEY is not set');

    if (!chatHistories.has(chatId)) {
        chatHistories.set(chatId, []);
    }
    const history = chatHistories.get(chatId);

    history.push({ role: 'user', parts: newParts });

    if (history.length > 20) {
        history.splice(0, history.length - 20);
    }

    let lastError;
    for (const model of MODEL_CHAIN) {
        try {
            const text = await callGemini(model, history, temperature);
            if (text) {
                const cleaned = cleanReply(text);
                history.push({ role: 'model', parts: [{ text: cleaned }] });
                return cleaned;
            }
            return FALLBACK_REPLY;
        } catch (e) {
            lastError = e;
            console.error(String(e.message));
            if ([400, 404, 429, 500, 502, 503, 504].includes(e.status)) continue;
            throw e;
        }
    }
    throw lastError || new Error('No model available');
}

async function telegram(method, payload) {
    const token = process.env.TELEGRAM_BOT_TOKEN;
    if (!token) throw new Error('TELEGRAM_BOT_TOKEN is not set');
    const r = await fetch(`https://api.telegram.org/bot${token}/${method}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
    });
    const body = await r.text();
    if (!r.ok) throw new Error(`Telegram ${method} HTTP ${r.status}: ${body.slice(0, 300)}`);
    try { return JSON.parse(body); } catch (_) { return {}; }
}

async function sendTelegramMessage(chatId, text, replyToMessageId) {
    const LIMIT = 4000;
    const chunks = [];
    for (let i = 0; i < text.length; i += LIMIT) chunks.push(text.slice(i, i + LIMIT));
    for (let i = 0; i < chunks.length; i++) {
        const payload = { chat_id: chatId, text: chunks[i] };
        if (i === 0 && replyToMessageId) {
            payload.reply_parameters = { message_id: replyToMessageId, allow_sending_without_reply: true };
        }
        await telegram('sendMessage', payload);
    }
}

async function fetchTelegramImage(msg) {
    let fileId = null;
    let mime = 'image/jpeg';
    let size = 0;

    if (Array.isArray(msg.photo) && msg.photo.length) {
        const best = msg.photo[msg.photo.length - 1];
        fileId = best.file_id;
        size = best.file_size || 0;
    } else if (msg.document && /^image\//.test(msg.document.mime_type || '')) {
        fileId = msg.document.file_id;
        mime = msg.document.mime_type;
        size = msg.document.file_size || 0;
    } else if (msg.sticker && !msg.sticker.is_animated && !msg.sticker.is_video) {
        fileId = msg.sticker.file_id;
        mime = 'image/webp';
        size = msg.sticker.file_size || 0;
    }
    if (!fileId || size > MAX_IMAGE_BYTES) return null;

    const info = await telegram('getFile', { file_id: fileId });
    const filePath = info && info.result && info.result.file_path;
    if (!filePath) return null;

    const r = await fetch(`https://api.telegram.org/file/bot${process.env.TELEGRAM_BOT_TOKEN}/${filePath}`);
    if (!r.ok) throw new Error(`Telegram file download HTTP ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length > MAX_IMAGE_BYTES) return null;
    return { inline_data: { mime_type: mime, data: buf.toString('base64') } };
}

function parseBody(req) {
    if (typeof req.body === 'string') {
        try { return JSON.parse(req.body); } catch (_) { return null; }
    }
    return req.body || null;
}

module.exports = async (req, res) => {
    if (req.method === 'GET') {
        const query = req.query || {};
        if (query.cron !== 'true') {
            return res.status(200).json({ status: 'Tang Jee Rina Webhook API Operational' });
        }

        const secret = process.env.CRON_SECRET;
        if (!secret || req.headers['authorization'] !== `Bearer ${secret}`) {
            return res.status(401).json({ error: 'Unauthorized cron request' });
        }

        const chatIds = String(query.chat_id || process.env.CRON_CHAT_ID || '')
            .split(',').map((s) => s.trim()).filter(Boolean);
        if (!chatIds.length) {
            return res.status(400).json({ error: 'Missing chat_id (query) or CRON_CHAT_ID (env)' });
        }

        try {
            for (const id of chatIds) {
                const text = await generateReplyWithHistory(id, [{
                    text: 'Напиши первая в чат без повода. Выдай дерзкую, эпатажную или провокационную реплику от лица Танг Джи Рины.'
                }]);
                await sendTelegramMessage(id, text);
            }
            return res.status(200).json({ status: 'Proactive message dispatched', chats: chatIds.length });
        } catch (e) {
            console.error('Cron error:', e);
            return res.status(500).json({ error: e.message });
        }
    }

    if (req.method === 'POST') {
        const expected = process.env.TELEGRAM_WEBHOOK_SECRET;
        if (expected && req.headers['x-telegram-bot-api-secret-token'] !== expected) {
            return res.status(401).json({ error: 'Bad webhook secret' });
        }

        const update = parseBody(req);
        const msg = update && update.message;
        if (!msg || !msg.chat) {
            return res.status(200).json({ status: 'No message payload' });
        }

        const chatId = msg.chat.id;
        let userText = msg.text || msg.caption || '';
        if (/^\/start(@\w+)?(\s|$)/.test(userText)) {
            userText = 'Привет! (человек только что запустил бота - поздоровайся в образе)';
        }

        try {
            telegram('sendChatAction', { chat_id: chatId, action: 'typing' }).catch(() => {});

            const replied = msg.reply_to_message;
            const repliedText = replied && (replied.text || replied.caption);
            const context = repliedText ? `[Он отвечает на сообщение: "${repliedText.slice(0, 500)}"]\n` : '';

            let image = null;
            try {
                image = await fetchTelegramImage(msg);
            } catch (e) {
                console.error('Image fetch error:', e.message);
            }

            const parts = [];
            if (image) {
                parts.push({ text: context + (userText || '(человек прислал картинку без подписи - отреагируй на неё в образе)') });
                parts.push(image);
            } else {
                parts.push({ text: context + (userText || 'Привет') });
            }

            const botReply = await generateReplyWithHistory(chatId, parts);
            await sendTelegramMessage(chatId, botReply);
            return res.status(200).json({ status: 'success' });
        } catch (error) {
            console.error('Webhook processing error:', error);
            try { await sendTelegramMessage(chatId, FALLBACK_REPLY); } catch (_) {}
            return res.status(200).json({ status: 'error_handled', message: error.message });
        }
    }

    return res.status(405).json({ error: 'Method not allowed' });
};
