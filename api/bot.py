# Обработчик команды /start
async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Я грызун! Мой голова - идеальный компьютер, "
        "я способна думать на все 100! Ча те надо,бе́нда́н?🥱"
    )

# Обработчик обычных сообщений
async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_text = update.message.text
    await context.bot.send_chat_action(
        chat_id=update.effective_chat.id, action="typing"
    )
    try:
        response = ai_client.models.generate_content(
            model="gemini-2.5-flash",
            contents=user_text,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_INSTRUCTION
            ),
        )
        await update.message.reply_text(response.text)
    except Exception as e:
        logging.error(f"Ошибка Gemini: {e}")
        await update.message.reply_text(
            "Чщщщщ, мой идеальный компьютер дал сбой... "
            "Попробуй еще раз, колхозан, думалку давненько не врублял"
        )

# Внутренняя async-обработка (создается заново при каждом запросе Vercel)
async def _process_update(body):
    app = Application.builder().token(TELEGRAM_TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(
        MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message)
    )
    await app.initialize()

    data = json.loads(body)
    update = Update.de_json(data, app.bot)
    await app.process_update(update)
    await app.shutdown()

# ГЛАВНЫЙ ОБРАБОТЧИК ДЛЯ VERCEL (Синхронный!)
def handler(request):
    if request.method == "POST":
        try:
            asyncio.run(_process_update(request.body))
            return ("OK", 200)
        except Exception as e:
            logging.exception("Ошибка обработки обновления")
            return (f"Error: {e}", 500)

    return ("OK", 200)
